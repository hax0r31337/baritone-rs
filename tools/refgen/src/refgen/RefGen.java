    private static JsonObject rotationUtils() {
        JsonObject o = new JsonObject();

        // [orig xyz, dest xyz, current yaw, current pitch, plain yaw, plain pitch, relative yaw, relative pitch]
        JsonArray fromVec = new JsonArray();
        for (int i = 0; i < 400; i++) {
            Vec3 a = randVec();
            Vec3 b = i % 10 == 0 ? a : randVec();
            Rotation current = new Rotation(randAngle(), randAngle());
            Rotation plain = calcRotationFromVec3d(a, b);
            if (i % 5 == 0) {
                current = new Rotation(plain.getYaw() + 360F * (R.nextInt(5) - 2) + (R.nextFloat() - 0.5F) * 0.03F, randAngle());
            }
            Rotation rel = calcRotationFromVec3d(a, b, current);
            fromVec.add(row(d(a.x), d(a.y), d(a.z), d(b.x), d(b.y), d(b.z), f(current.getYaw()), f(current.getPitch()),
                    f(plain.getYaw()), f(plain.getPitch()), f(rel.getYaw()), f(rel.getPitch())));
        }
        o.add("calc_rotation_from_vec3d", fromVec);

        // [orig xyz, dest xyz, yaw, pitch]
        JsonArray fromCoords = new JsonArray();
        for (int i = 0; i < 200; i++) {
            BlockPos a = new BlockPos(R.nextInt(2000) - 1000, R.nextInt(400) - 64, R.nextInt(2000) - 1000);
            BlockPos b = i % 3 == 0 ? a.offset(R.nextInt(9) - 4, R.nextInt(9) - 4, R.nextInt(9) - 4) : new BlockPos(randInt(), randInt(), randInt());
            Rotation r = calcRotationFromCoords(a, b);
            fromCoords.add(row(a.getX(), a.getY(), a.getZ(), b.getX(), b.getY(), b.getZ(), f(r.getYaw()), f(r.getPitch())));
        }
        o.add("calc_rotation_from_coords", fromCoords);

        // [yaw, pitch, x, y, z]
        JsonArray look = new JsonArray();
        for (int i = 0; i < 400; i++) {
            Rotation r = new Rotation(randAngle(), randAngle());
            Vec3 v = calcLookDirectionFromRotation(r);
            look.add(row(f(r.getYaw()), f(r.getPitch()), d(v.x), d(v.y), d(v.z)));
        }
        o.add("calc_look_direction_from_rotation", look);
        return o;
    }

