    private static JsonObject rotation() {
        JsonObject o = new JsonObject();

        // [in, normalizeYaw, clampPitch]
        JsonArray single = new JsonArray();
        for (int i = 0; i < 300; i++) {
            float v = randAngle();
            single.add(row(f(v), f(Rotation.normalizeYaw(v)), f(Rotation.clampPitch(v))));
        }
        o.add("normalize_clamp", single);

        // [yaw, offsetYaw, yawDistanceFromOffset]
        JsonArray yawDistance = new JsonArray();
        for (int i = 0; i < 300; i++) {
            float a = randAngle(), b = randAngle();
            yawDistance.add(row(f(a), f(b), f(Rotation.yawDistanceFromOffset(a, b))));
        }
        o.add("yaw_distance_from_offset", yawDistance);

        // [ay, ap, by, bp, add.yaw, add.pitch, subtract.yaw, subtract.pitch,
        //  normalizeAndClamp(a).yaw, normalizeAndClamp(a).pitch, isReallyCloseTo, yawIsReallyClose]
        JsonArray pairs = new JsonArray();
        for (int i = 0; i < 400; i++) {
            Rotation a = new Rotation(randAngle(), randAngle());
            Rotation b;
            switch (i % 4) {
                case 0 -> b = new Rotation(a.getYaw() + (R.nextFloat() - 0.5F) * 0.03F, a.getPitch() + (R.nextFloat() - 0.5F) * 0.03F);
                case 1 -> b = new Rotation(a.getYaw() + 360F * (R.nextInt(5) - 2) + (R.nextFloat() - 0.5F) * 0.03F, a.getPitch());
                default -> b = new Rotation(randAngle(), randAngle());
            }
            Rotation add = a.add(b);
            Rotation sub = a.subtract(b);
            Rotation nc = a.normalizeAndClamp();
            pairs.add(row(f(a.getYaw()), f(a.getPitch()), f(b.getYaw()), f(b.getPitch()),
                    f(add.getYaw()), f(add.getPitch()), f(sub.getYaw()), f(sub.getPitch()),
                    f(nc.getYaw()), f(nc.getPitch()), a.isReallyCloseTo(b), a.yawIsReallyClose(b)));
        }
        o.add("pairs", pairs);
        return o;
    }

    // region RotationUtils: pure methods copied verbatim from upstream RotationUtils (it cannot be
    // compiled standalone, it depends on IPlayerContext / LookBehavior)

    private static final double RAD_TO_DEG = 180.0 / Math.PI;
    private static final float DEG_TO_RAD_F = (float) (Math.PI / 180.0);

    private static Rotation calcRotationFromCoords(BlockPos orig, BlockPos dest) {
        return calcRotationFromVec3d(new Vec3(orig.getX(), orig.getY(), orig.getZ()), new Vec3(dest.getX(), dest.getY(), dest.getZ()));
    }

    private static Rotation wrapAnglesToRelative(Rotation current, Rotation target) {
        if (current.yawIsReallyClose(target)) {
            return new Rotation(current.getYaw(), target.getPitch());
        }
        return target.subtract(current).normalize().add(current);
    }

    private static Rotation calcRotationFromVec3d(Vec3 orig, Vec3 dest, Rotation current) {
        return wrapAnglesToRelative(current, calcRotationFromVec3d(orig, dest));
    }

    private static Rotation calcRotationFromVec3d(Vec3 orig, Vec3 dest) {
        double[] delta = {orig.x - dest.x, orig.y - dest.y, orig.z - dest.z};
        double yaw = Mth.atan2(delta[0], -delta[2]);
        double dist = Math.sqrt(delta[0] * delta[0] + delta[2] * delta[2]);
        double pitch = Mth.atan2(delta[1], dist);
        return new Rotation(
                (float) (yaw * RAD_TO_DEG),
                (float) (pitch * RAD_TO_DEG)
        );
    }

    private static Vec3 calcLookDirectionFromRotation(Rotation rotation) {
        float flatZ = Mth.cos((-rotation.getYaw() * DEG_TO_RAD_F) - (float) Math.PI);
        float flatX = Mth.sin((-rotation.getYaw() * DEG_TO_RAD_F) - (float) Math.PI);
        float pitchBase = -Mth.cos(-rotation.getPitch() * DEG_TO_RAD_F);
        float pitchHeight = Mth.sin(-rotation.getPitch() * DEG_TO_RAD_F);
        return new Vec3(flatX * pitchBase, pitchHeight, flatZ * pitchBase);
    }

