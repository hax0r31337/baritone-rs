    private static JsonObject betterBlockPos() {
        JsonObject o = new JsonObject();

        // [x, y, z, longHash, hashCode]
        JsonArray hashes = new JsonArray();
        for (int i = 0; i < 300; i++) {
            int x = randInt(), y = randInt(), z = randInt();
            hashes.add(row(x, y, z, BetterBlockPos.longHash(x, y, z), new BetterBlockPos(x, y, z).hashCode()));
        }
        o.add("hash", hashes);

        // [x, y, z, serializeToLong, deserialized x, y, z]
        JsonArray serialize = new JsonArray();
        for (int i = 0; i < 300; i++) {
            int x = randInt(), y = randInt(), z = randInt();
            long s = BetterBlockPos.serializeToLong(x, y, z);
            BetterBlockPos back = BetterBlockPos.deserializeFromLong(s);
            serialize.add(row(x, y, z, s, back.x, back.y, back.z));
        }
        o.add("serialize", serialize);

        // [serialized, x, y, z] for arbitrary longs
        JsonArray deserialize = new JsonArray();
        for (int i = 0; i < 100; i++) {
            long s = R.nextLong();
            BetterBlockPos p = BetterBlockPos.deserializeFromLong(s);
            deserialize.add(row(s, p.x, p.y, p.z));
        }
        o.add("deserialize", deserialize);

        // [x, y, z (double bits), x, y, z]
        JsonArray fromDouble = new JsonArray();
        for (int i = 0; i < 200; i++) {
            double x = randDouble(), y = randDouble(), z = randDouble();
            BetterBlockPos p = new BetterBlockPos(x, y, z);
            fromDouble.add(row(d(x), d(y), d(z), p.x, p.y, p.z));
        }
        o.add("from_double", fromDouble);

        // [x1, y1, z1, x2, y2, z2, distanceSq, distanceTo]
        JsonArray distance = new JsonArray();
        for (int i = 0; i < 200; i++) {
            BetterBlockPos a = new BetterBlockPos(randInt(), randInt(), randInt());
            BetterBlockPos b = new BetterBlockPos(randInt(), randInt(), randInt());
            distance.add(row(a.x, a.y, a.z, b.x, b.y, b.z, d(a.distanceSq(b)), d(a.distanceTo(b))));
        }
        o.add("distance", distance);

        // [x, y, z, amt, above(amt), below(amt), north(amt), south(amt), east(amt), west(amt),
        //  relative(DOWN..EAST, amt)...] each result flattened as x, y, z
        JsonArray offsets = new JsonArray();
        for (int i = 0; i < 200; i++) {
            BetterBlockPos p = new BetterBlockPos(randInt(), randInt(), randInt());
            int amt = i % 4 == 0 ? 1 : randInt();
            JsonArray r = row(p.x, p.y, p.z, amt);
            List<BetterBlockPos> results = new ArrayList<>(List.of(
                    p.above(amt), p.below(amt), p.north(amt), p.south(amt), p.east(amt), p.west(amt)));
            for (Direction dir : Direction.values()) {
                results.add(p.relative(dir, amt));
            }
            for (BetterBlockPos q : results) {
                r.add(q.x);
                r.add(q.y);
                r.add(q.z);
            }
            offsets.add(r);
        }
        o.add("offsets", offsets);

        // unit offsets: [x, y, z, above(), below(), north(), south(), east(), west(), relative(DOWN..EAST)...]
        JsonArray unit = new JsonArray();
        for (int i = 0; i < 50; i++) {
            BetterBlockPos p = new BetterBlockPos(randInt(), randInt(), randInt());
            JsonArray r = row(p.x, p.y, p.z);
            List<BetterBlockPos> results = new ArrayList<>(List.of(
                    p.above(), p.below(), p.north(), p.south(), p.east(), p.west()));
            for (Direction dir : Direction.values()) {
                results.add(p.relative(dir));
            }
            for (BetterBlockPos q : results) {
                r.add(q.x);
                r.add(q.y);
                r.add(q.z);
            }
            unit.add(r);
        }
        o.add("unit_offsets", unit);

        JsonArray strings = new JsonArray();
        for (BetterBlockPos p : new BetterBlockPos[]{BetterBlockPos.ORIGIN, new BetterBlockPos(-12, 345, Integer.MIN_VALUE)}) {
            strings.add(row(p.x, p.y, p.z, p.toString()));
        }
        o.add("to_string", strings);
        return o;
    }

    private static JsonObject mth() throws ReflectiveOperationException {
        JsonObject o = new JsonObject();

        float[] sinTable = (float[]) staticField(Mth.class, "SIN");
        // FNV-1a over the raw bits of each entry, one 32 bit word at a time
        long h = 0xcbf29ce484222325L;
        for (float v : sinTable) {
            h ^= Float.floatToRawIntBits(v) & 0xFFFFFFFFL;
            h *= 0x100000001b3L;
        }
        o.addProperty("sin_table_len", sinTable.length);
        o.addProperty("sin_table_fnv", h);
        JsonArray sinSamples = new JsonArray();
        for (int i = 0; i < 512; i++) {
            int idx = i < 16 ? i * 4096 : R.nextInt(sinTable.length);
            sinSamples.add(row(idx, f(sinTable[idx])));
        }
        o.add("sin_table_samples", sinSamples);

        JsonArray asinTab = new JsonArray();
        for (double v : (double[]) staticField(Mth.class, "ASIN_TAB")) {
            asinTab.add(d(v));
        }
        o.add("asin_tab", asinTab);
        JsonArray cosTab = new JsonArray();
        for (double v : (double[]) staticField(Mth.class, "COS_TAB")) {
            cosTab.add(d(v));
        }
        o.add("cos_tab", cosTab);
        o.add("frac_bias", d((double) staticField(Mth.class, "FRAC_BIAS")));

        // [in, sin, cos]
        JsonArray sinCos = new JsonArray();
        for (int i = 0; i < 400; i++) {
            double v = i < 100 ? (R.nextDouble() - 0.5) * 20 : randDouble();
            sinCos.add(row(d(v), f(Mth.sin(v)), f(Mth.cos(v))));
        }
        o.add("sin_cos", sinCos);

        // [y, x, atan2]
        JsonArray atan2 = new JsonArray();
        double[] specials = {0.0, -0.0, 1.0, -1.0, 1e-300, Double.POSITIVE_INFINITY, Double.NEGATIVE_INFINITY, Double.NaN};
        for (double y : specials) {
            for (double x : specials) {
                atan2.add(row(d(y), d(x), d(Mth.atan2(y, x))));
            }
        }
        for (int i = 0; i < 500; i++) {
            double y = i < 250 ? (R.nextDouble() - 0.5) * 20 : randDouble();
            double x = i < 250 ? (R.nextDouble() - 0.5) * 20 : randDouble();
            atan2.add(row(d(y), d(x), d(Mth.atan2(y, x))));
        }
        o.add("atan2", atan2);

        // [in, fastInvSqrt]
        JsonArray invSqrt = new JsonArray();
        for (int i = 0; i < 200; i++) {
            double v = i < 100 ? R.nextDouble() * 100 : randDouble();
            invSqrt.add(row(d(v), d(Mth.fastInvSqrt(v))));
        }
        o.add("fast_inv_sqrt", invSqrt);

        // [in, floor]
        JsonArray floor = new JsonArray();
        for (int i = 0; i < 300; i++) {
            double v = randDouble();
            floor.add(row(d(v), Mth.floor(v)));
        }
        o.add("floor", floor);

        // [in, wrapDegrees(float)]
        JsonArray wrapF = new JsonArray();
        for (int i = 0; i < 300; i++) {
            float v = i < 10 ? new float[]{Float.NaN, Float.POSITIVE_INFINITY, 180F, -180F, 540F, -540F, 0F, -0F, 1e20F, -1e20F}[i] : randAngle();
            wrapF.add(row(f(v), f(Mth.wrapDegrees(v))));
        }
        o.add("wrap_degrees_f32", wrapF);

        // [in, wrapDegrees(double)]
        JsonArray wrapD = new JsonArray();
        for (int i = 0; i < 300; i++) {
            double v = i % 2 == 0 ? randDouble() : randAngle();
            wrapD.add(row(d(v), d(Mth.wrapDegrees(v))));
        }
        o.add("wrap_degrees_f64", wrapD);
        return o;
    }

