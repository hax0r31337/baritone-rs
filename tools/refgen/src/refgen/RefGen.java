    private static JsonObject spec(String kind, Object... kv) {
        JsonObject o = new JsonObject();
        o.addProperty("kind", kind);
        for (int i = 0; i < kv.length; i += 2) {
            Object v = kv[i + 1];
            o.add((String) kv[i], v instanceof JsonElement e ? e : v == null ? JsonNull.INSTANCE : row(v).get(0));
        }
        return o;
    }

    private record GoalCase(JsonObject spec, Goal goal, BlockPos anchor) {}

    private static GoalCase block(int x, int y, int z) {
        return new GoalCase(spec("GoalBlock", "x", x, "y", y, "z", z), new GoalBlock(x, y, z), new BlockPos(x, y, z));
    }

    private static GoalCase xz(int x, int z) {
        return new GoalCase(spec("GoalXZ", "x", x, "z", z), new GoalXZ(x, z), new BlockPos(x, 64, z));
    }

    private static GoalCase yLevel(int level) {
        return new GoalCase(spec("GoalYLevel", "level", level), new GoalYLevel(level), new BlockPos(0, level, 0));
    }

    private static GoalCase runAway(double distance, Integer maintainY, BlockPos... from) {
        JsonArray fromJson = new JsonArray();
        BetterBlockPos[] better = new BetterBlockPos[from.length];
        for (int i = 0; i < from.length; i++) {
            fromJson.add(pos(from[i]));
            better[i] = new BetterBlockPos(from[i]);
        }
        return new GoalCase(spec("GoalRunAway", "distance", d(distance), "maintain_y", maintainY, "from", fromJson),
                new GoalRunAway(distance, maintainY, better), from[0]);
    }

    private static GoalCase composite(GoalCase... cases) {
        JsonArray specs = new JsonArray();
        Goal[] goals = new Goal[cases.length];
        for (int i = 0; i < cases.length; i++) {
            specs.add(cases[i].spec);
            goals[i] = cases[i].goal;
        }
        return new GoalCase(spec("GoalComposite", "goals", specs), new GoalComposite(goals),
                cases.length == 0 ? BlockPos.ZERO : cases[0].anchor);
    }

    private static GoalCase inverted(GoalCase origin) {
        return new GoalCase(spec("GoalInverted", "origin", origin.spec), new GoalInverted(origin.goal), origin.anchor);
    }

    private static JsonArray goals() {
        List<GoalCase> cases = new ArrayList<>();
        cases.add(block(10, 64, -20));
        cases.add(block(2147483000, -2147483000, 5));
        cases.add(new GoalCase(spec("GoalTwoBlocks", "x", 0, "y", 70, "z", 0), new GoalTwoBlocks(0, 70, 0), new BlockPos(0, 70, 0)));
        cases.add(new GoalCase(spec("GoalGetToBlock", "x", -5, "y", 12, "z", 7), new GoalGetToBlock(new BlockPos(-5, 12, 7)), new BlockPos(-5, 12, 7)));
        for (int[] n : new int[][]{{100, 64, 100, 3}, {0, 0, 0, 0}, {-7, 5, 3, 1}, {1, 2, 3, 6}}) {
            BlockPos p = new BlockPos(n[0], n[1], n[2]);
            cases.add(new GoalCase(spec("GoalNear", "x", n[0], "y", n[1], "z", n[2], "range", n[3]), new GoalNear(p, n[3]), p));
        }
        cases.add(xz(123, -456));
        cases.add(xz(Integer.MAX_VALUE, Integer.MIN_VALUE));
        cases.add(yLevel(64));
        cases.add(yLevel(-59));
        cases.add(new GoalCase(spec("GoalAxis"), new GoalAxis(), new BlockPos(0, 120, 0)));
        for (Direction dir : new Direction[]{Direction.NORTH, Direction.EAST, Direction.SOUTH, Direction.WEST}) {
            BlockPos p = new BlockPos(10, 64, -10);
            cases.add(new GoalCase(spec("GoalStrictDirection", "x", p.getX(), "y", p.getY(), "z", p.getZ(), "direction", dir.getName()),
                    new GoalStrictDirection(p, dir), p));
        }
        cases.add(runAway(5.5, null, new BlockPos(0, 64, 0)));
        cases.add(runAway(3, 70, new BlockPos(10, 64, 10), new BlockPos(-10, 64, -10)));
        cases.add(runAway(4, null, new BlockPos(-3, 64, 2), new BlockPos(5, 60, 5)));
        cases.add(composite(block(1, 2, 3), xz(100, 100), yLevel(12)));
        cases.add(composite());
        cases.add(inverted(block(0, 64, 0)));
        cases.add(inverted(composite(block(5, 5, 5), yLevel(-10))));

        JsonArray out = new JsonArray();
        for (GoalCase c : cases) {
            JsonObject o = new JsonObject();
            o.add("spec", c.spec);
            o.addProperty("to_string", c.goal.toString());
            o.add("heuristic_at_goal", d(c.goal.heuristic()));
            // [x, y, z, isInGoal, heuristic]
            JsonArray samples = new JsonArray();
            for (int i = 0; i < 250; i++) {
                int x, y, z;
                if (i < 125) {
                    x = c.anchor.getX() + R.nextInt(13) - 6;
                    y = c.anchor.getY() + R.nextInt(13) - 6;
                    z = c.anchor.getZ() + R.nextInt(13) - 6;
                } else if (i < 200) {
                    x = R.nextInt(4000) - 2000;
                    y = R.nextInt(384) - 64;
                    z = R.nextInt(4000) - 2000;
                } else {
                    x = randInt();
                    y = randInt();
                    z = randInt();
                }
                samples.add(row(x, y, z, c.goal.isInGoal(x, y, z), d(c.goal.heuristic(x, y, z))));
            }
            o.add("samples", samples);
            out.add(o);
        }
        return out;
    }

